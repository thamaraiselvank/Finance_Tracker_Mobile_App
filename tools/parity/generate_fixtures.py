    values: list[float] = [
        0.125, 0.375, 2.675, 1.005, 2.5, 3.5, -0.125, -2.5, 0.5, 1.5, 0.045, 1234567.125,
        19566.165, 0.0, 100.0, 33.335, 66.665, 1e-07, 123456789.995, 7.0 / 3.0, 2.0 / 3.0,
    ]
    values += [rng.uniform(-1_000_000, 1_000_000) for _ in range(400)]
