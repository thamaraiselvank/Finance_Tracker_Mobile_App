def _json_safe(value: Any) -> Any:
    """Round-trip through JSON so dates, Decimals etc. look exactly as the API sends them."""
    return json.loads(json.dumps(value, default=str))


def _validation_error(error: ValidationError) -> dict[str, Any]:
    """First validation problem, in the shape the app shows to the user."""
    first = error.errors()[0]
    loc = [str(part) for part in first.get("loc", ())]
    return {
        "field": loc[-1] if loc else None,
        "message": str(first["msg"]).removeprefix("Value error, "),
    }


def _run_case(
    input_data: dict[str, Any],
    input_model: type[BaseModel],
    compute: Callable[[Any], Any],
    output_model: type[BaseModel] | None = None,
) -> dict[str, Any]:
    case: dict[str, Any] = {"input": input_data}
    try:
        payload = input_model.model_validate(input_data)
    except ValidationError as error:
        case["error"] = _validation_error(error)
        return case
    try:
        result = compute(payload)
    except ValueError as error:
        case["error"] = {"field": None, "message": str(error)}
        return case
    if output_model is not None:
        result = output_model.model_validate(result).model_dump(mode="json")
    case["output"] = _json_safe(result)
    return case


